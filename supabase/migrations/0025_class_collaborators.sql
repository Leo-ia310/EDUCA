-- Class ownership is administered centrally. A collaborator cannot make themself
-- the titular or create a different class to bypass per-class grants.
create or replace function public.class_admin_actor() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.users u join public.user_roles ur on ur.user_id=u.id join public.roles r on r.id=ur.role_id
 where u.auth_user_id=auth.uid() and u.institution_id=public.current_institution_id() and u.active and u.deleted_at is null and r.code in ('admin','coordinator','director','super_admin'));
$$;
drop policy if exists class_admin_write on public.classes;
create policy class_admin_write on public.classes as restrictive for all to authenticated using (true) with check (public.class_admin_actor());
drop policy if exists class_admin_delete on public.classes;
create policy class_admin_delete on public.classes as restrictive for delete to authenticated using (public.class_admin_actor());
-- Ownership/role identity cannot be rewritten to turn a collaborator into an
-- owner. Keep ordinary self-service notification/profile fields writable.
do $$ declare tbl text; cmd text; begin
 foreach tbl in array array['teachers','user_roles','roles'] loop
   foreach cmd in array array['insert','update','delete'] loop
     execute format('drop policy if exists collaboration_identity_%s on public.%I',cmd,tbl);
     if cmd='insert' then execute format('create policy collaboration_identity_insert on public.%I as restrictive for insert to authenticated with check(public.class_admin_actor())',tbl);
     elsif cmd='update' then execute format('create policy collaboration_identity_update on public.%I as restrictive for update to authenticated using(public.class_admin_actor()) with check(public.class_admin_actor())',tbl);
     else execute format('create policy collaboration_identity_delete on public.%I as restrictive for delete to authenticated using(public.class_admin_actor())',tbl); end if;
   end loop;
 end loop;
end $$;
create or replace function public.guard_collaboration_identity() returns trigger language plpgsql security definer set search_path=public as $$
begin
 if auth.uid() is not null and not public.class_admin_actor() and (
   old.auth_user_id is distinct from auth.uid() or new.auth_user_id is distinct from old.auth_user_id
   or new.person_id is distinct from old.person_id or new.institution_id is distinct from old.institution_id
   or new.admin_permissions is distinct from old.admin_permissions or new.active is distinct from old.active
   or new.deleted_at is distinct from old.deleted_at) then
   raise exception 'No puedes cambiar la identidad ni los permisos de esta cuenta.' using errcode='42501';
 end if;
 return new;
end $$;
