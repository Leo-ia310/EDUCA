-- Wrap the legacy SECURITY DEFINER grading RPC: RLS does not protect its body.
do $$ begin
 if to_regprocedure('public.grade_submission_internal(bigint,numeric,text)') is null then
   alter function public.grade_submission(bigint,numeric,text) rename to grade_submission_internal;
 end if;
end $$;
revoke all on function public.grade_submission_internal(bigint,numeric,text) from public,anon,authenticated;
create or replace function public.grade_submission(p_submission_id bigint,p_score numeric,p_feedback text default null) returns bigint
language plpgsql security definer set search_path=public as $$
declare cid bigint; result bigint; actor bigint;
begin
 -- Serialize grading within an assignment, so two collaborators cannot create
 -- competing evaluations or grade a submission moved during authorization.
 select a.class_id into cid from public.submissions s join public.assignments a on a.id=s.assignment_id
 where s.id=p_submission_id and s.institution_id=public.current_institution_id() for update of a,s;
 if cid is null or not public.class_permission(cid,'assignments.grade') then raise exception 'No tienes permiso para calificar esta tarea.' using errcode='42501'; end if;
 if p_score is null or p_score<0 then raise exception 'Nota inválida.' using errcode='22023'; end if;
 select id into actor from public.users where auth_user_id=auth.uid();
 result:=public.grade_submission_internal(p_submission_id,p_score,p_feedback);
 update public.grades set recorded_by=actor where id=result;
 return result;
end $$;

-- Audit records are generated with the authenticated actor, including RPCs.
create or replace function public.ensure_collaborative_class_session(p_class_id bigint,p_date date) returns bigint
language plpgsql security definer set search_path=public as $$
declare result bigint; cls public.classes%rowtype; teacher bigint;
begin
 if p_date is null or not public.class_permission(p_class_id,'attendance.write') then
   raise exception 'No tienes permiso para registrar asistencia.' using errcode='42501'; end if;
 select * into cls from public.classes where id=p_class_id and institution_id=public.current_institution_id();
 select t.id into teacher from public.teachers t join public.users u on u.person_id=t.person_id and u.institution_id=t.institution_id
   where u.auth_user_id=auth.uid() and t.active and u.active and u.deleted_at is null;
 if teacher is null then raise exception 'Tu cuenta no está enlazada a un docente.' using errcode='42501'; end if;
 perform pg_advisory_xact_lock(hashtextextended('class-session/'||p_class_id||'/'||p_date,0));
 select id into result from public.class_sessions where class_id=p_class_id and institution_id=cls.institution_id and date=p_date order by id limit 1;
 if result is null then
   insert into public.class_sessions(institution_id,class_id,group_id,date,recorded_by,synced)
   values(cls.institution_id,cls.id,cls.group_id,p_date,teacher,true) returning id into result;
 end if;
 return result;
end $$;
revoke all on function public.ensure_collaborative_class_session(bigint,date) from public,anon;
grant execute on function public.ensure_collaborative_class_session(bigint,date) to authenticated;

create or replace function public.audit_class_action() returns trigger language plpgsql security definer set search_path=public as $$
declare before_row jsonb; after_row jsonb; actor bigint; inst bigint;
begin
 select id,institution_id into actor,inst from public.users where auth_user_id=auth.uid();
 if actor is null then return null; end if;
 if tg_op<>'INSERT' then before_row:=to_jsonb(old); end if;
 if tg_op<>'DELETE' then after_row:=to_jsonb(new); end if;
 insert into public.audit_log(institution_id,user_id,table_name,record_id,action,data_before,data_after)
 values(inst,actor,tg_table_name,coalesce(after_row->>'id',before_row->>'id'),tg_op,before_row,after_row);
 return null;
end $$;
do $$ declare tbl text; begin
 foreach tbl in array array['class_collaborators','assignments','submissions','evaluations','grades','class_sessions','attendances'] loop
   execute format('drop trigger if exists class_action_audit on public.%I',tbl);
   execute format('create trigger class_action_audit after insert or update or delete on public.%I for each row execute function public.audit_class_action()',tbl);
 end loop;
end $$;
