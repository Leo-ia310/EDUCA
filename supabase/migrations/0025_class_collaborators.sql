-- Class-scoped collaboration. No grants exist until the invited teacher accepts.
create table if not exists public.class_collaborators (
  id bigint generated by default as identity primary key,
  institution_id bigint not null references public.institutions(id),
  class_id bigint not null references public.classes(id) on delete cascade,
  teacher_id bigint not null references public.teachers(id),
  teacher_user_id bigint not null references public.users(id),
  invited_by bigint not null references public.users(id),
  permissions text[] not null,
  status text not null default 'pending' check(status in ('pending','active','declined','revoked')),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  responded_at timestamptz,
  unique(class_id,teacher_user_id),
  check(permissions <@ array['class.view','students.view','assignments.create','assignments.review','assignments.grade','grades.write','attendance.write']::text[]),
  check('class.view'=any(permissions))
);
create index if not exists class_collaborators_user_active on public.class_collaborators(teacher_user_id,class_id) where status='active';
alter table public.class_collaborators enable row level security;
revoke all on public.class_collaborators from anon,authenticated;
grant select on public.class_collaborators to authenticated;
grant all on public.class_collaborators to service_role;
grant usage,select on sequence public.class_collaborators_id_seq to service_role;

create or replace function public.class_permission(p_class_id bigint,p_permission text) returns boolean
language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.classes c join public.users u on u.institution_id=c.institution_id
   where c.id=p_class_id and c.active and c.institution_id=public.current_institution_id()
     and u.auth_user_id=auth.uid() and u.active and u.deleted_at is null and (
       exists(select 1 from public.user_roles ur join public.roles r on r.id=ur.role_id where ur.user_id=u.id and r.code in ('admin','coordinator','director','super_admin'))
       or exists(select 1 from public.teachers t where t.person_id=u.person_id and t.institution_id=c.institution_id and t.active
         and exists(select 1 from public.user_roles ur join public.roles r on r.id=ur.role_id where ur.user_id=u.id and r.code='teacher')
         and (t.id=c.teacher_id or (p_permission<>'collaborators.manage' and exists(
           select 1 from public.class_collaborators cc where cc.class_id=c.id and cc.institution_id=c.institution_id
             and cc.teacher_id=t.id and cc.teacher_user_id=u.id and cc.status='active' and p_permission=any(cc.permissions)))))
     ));
$$;
create or replace function public.is_teacher_actor() returns boolean language sql stable security definer set search_path=public as $$
 select exists(select 1 from public.users u join public.user_roles ur on ur.user_id=u.id join public.roles r on r.id=ur.role_id
   where u.auth_user_id=auth.uid() and u.institution_id=public.current_institution_id() and u.active and u.deleted_at is null and r.code='teacher')
 and not exists(select 1 from public.users u join public.user_roles ur on ur.user_id=u.id join public.roles r on r.id=ur.role_id
   where u.auth_user_id=auth.uid() and r.code in ('admin','coordinator','director','super_admin'));
$$;
create or replace function public.teacher_class_read(p_class_id bigint,p_permission text default 'class.view') returns boolean
language sql stable security definer set search_path=public as $$
 select not public.is_teacher_actor() or public.class_permission(p_class_id,p_permission);
$$;
create or replace function public.teacher_group_read(p_group_id bigint) returns boolean
language sql stable security definer set search_path=public as $$
 select not public.is_teacher_actor() or exists(select 1 from public.classes c where c.group_id=p_group_id and public.class_permission(c.id,'students.view'));
$$;
create or replace function public.teacher_student_read(p_student_id bigint) returns boolean
language sql stable security definer set search_path=public as $$
 select not public.is_teacher_actor() or exists(select 1 from public.enrollments e where e.student_id=p_student_id and public.teacher_group_read(e.group_id));
$$;
drop policy if exists collaboration_read on public.class_collaborators;
create policy collaboration_read on public.class_collaborators for select to authenticated using (
 institution_id=public.current_institution_id() and (public.class_permission(class_id,'collaborators.manage')
 or teacher_user_id=(select id from public.users where auth_user_id=auth.uid())));

-- Safe workspace also supplies the teacher picker and includes pending invites.
create or replace function public.collaboration_workspace() returns jsonb language plpgsql stable security definer set search_path=public as $$
declare actor public.users%rowtype; classes_json jsonb; invites_json jsonb; teachers_json jsonb;
begin
 select * into actor from public.users where auth_user_id=auth.uid() and institution_id=public.current_institution_id() and active and deleted_at is null;
 if actor.id is null or not exists(select 1 from public.user_roles ur join public.roles r on r.id=ur.role_id where ur.user_id=actor.id and r.code in ('teacher','admin','coordinator','director','super_admin')) then
   raise exception 'No tienes permiso para consultar colaboraciones.' using errcode='42501'; end if;
 select coalesce(jsonb_agg(x order by x->>'subjectName',x->>'groupName'),'[]') into classes_json from (
   select jsonb_build_object('classId',c.id,'groupId',c.group_id,'subjectName',s.name,'groupName',g.name,
     'isOwner',public.class_permission(c.id,'collaborators.manage'),
     'permissions',case when public.class_permission(c.id,'collaborators.manage') then to_jsonb(array['class.view','students.view','assignments.create','assignments.review','assignments.grade','grades.write','attendance.write','collaborators.manage'])
       else to_jsonb(cc.permissions) end) x
   from public.classes c join public.subjects s on s.id=c.subject_id join public.groups g on g.id=c.group_id
     left join public.class_collaborators cc on cc.class_id=c.id and cc.teacher_user_id=actor.id and cc.status='active'
   where c.institution_id=actor.institution_id and c.active and public.class_permission(c.id,'class.view')
 ) q;
 select coalesce(jsonb_agg(jsonb_build_object('id',cc.id,'classId',cc.class_id,'teacherUserId',cc.teacher_user_id,
   'teacherName',u.full_name,'inviterName',v.full_name,'subjectName',s.name,'groupName',g.name,
   'status',cc.status,'permissions',cc.permissions,'incoming',cc.teacher_user_id=actor.id,
   'canManage',public.class_permission(cc.class_id,'collaborators.manage')) order by cc.updated_at desc),'[]') into invites_json
 from public.class_collaborators cc join public.classes c on c.id=cc.class_id join public.subjects s on s.id=c.subject_id
 join public.groups g on g.id=c.group_id join public.users u on u.id=cc.teacher_user_id join public.users v on v.id=cc.invited_by
 where cc.institution_id=actor.institution_id and c.active and (cc.teacher_user_id=actor.id or public.class_permission(c.id,'collaborators.manage'));
 select coalesce(jsonb_agg(jsonb_build_object('userId',u.id,'name',u.full_name) order by u.full_name),'[]') into teachers_json
 from public.users u join public.teachers t on t.person_id=u.person_id and t.institution_id=u.institution_id and t.active
 where u.institution_id=actor.institution_id and u.id<>actor.id and u.active and u.deleted_at is null
 and exists(select 1 from public.user_roles ur join public.roles r on r.id=ur.role_id where ur.user_id=u.id and r.code='teacher');
 return jsonb_build_object('classes',classes_json,'invitations',invites_json,'teachers',teachers_json);
end $$;

create or replace function public.manage_class_collaboration(p_action text,p_class_ids bigint[] default null,p_teacher_user_id bigint default null,
 p_permissions text[] default null,p_invitation_id bigint default null) returns jsonb
language plpgsql security definer set search_path=public as $$
declare actor public.users%rowtype; target_teacher bigint; cls public.classes%rowtype; inv public.class_collaborators%rowtype;
 perms text[]; cid bigint; kind bigint;
begin
 select * into actor from public.users where auth_user_id=auth.uid() and institution_id=public.current_institution_id() and active and deleted_at is null;
 if actor.id is null then raise exception 'Usuario inválido.' using errcode='42501'; end if;
 if p_action in ('invite','update') then
   if p_permissions is null or not (p_permissions <@ array['class.view','students.view','assignments.create','assignments.review','assignments.grade','grades.write','attendance.write']::text[]) then
     raise exception 'Permisos de colaboración inválidos.' using errcode='22023'; end if;
   select array_agg(distinct p) into perms from unnest(p_permissions||array['class.view']||case when p_permissions && array['assignments.review','assignments.grade','grades.write','attendance.write'] then array['students.view'] else array[]::text[] end
     ||case when 'assignments.grade'=any(p_permissions) then array['assignments.review'] else array[]::text[] end) p;
 end if;
 if p_action='invite' then
   if cardinality(p_class_ids) is null or cardinality(p_class_ids)=0 or cardinality(p_class_ids)>100 or p_teacher_user_id=actor.id then
     raise exception 'Selecciona un profesor y entre una y cien clases.' using errcode='22023'; end if;
   select t.id into target_teacher from public.users u join public.teachers t on t.person_id=u.person_id and t.institution_id=u.institution_id
     where u.id=p_teacher_user_id and u.institution_id=actor.institution_id and u.active and u.deleted_at is null and t.active
       and exists(select 1 from public.user_roles ur join public.roles r on r.id=ur.role_id where ur.user_id=u.id and r.code='teacher');
   if target_teacher is null then raise exception 'El profesor debe estar activo en tu institución.' using errcode='42501'; end if;
   foreach cid in array p_class_ids loop
     select * into cls from public.classes where id=cid and institution_id=actor.institution_id and active for update;
     if not found or not public.class_permission(cid,'collaborators.manage') or cls.teacher_id=target_teacher then
       raise exception 'No tienes permiso para invitar en alguna de las clases seleccionadas.' using errcode='42501'; end if;
     if exists(select 1 from public.class_collaborators where class_id=cid and teacher_user_id=p_teacher_user_id and status in ('active','pending')) then
       raise exception 'El profesor ya tiene una invitación o acceso en esta clase. Edita sus permisos.' using errcode='22023'; end if;
     insert into public.class_collaborators(institution_id,class_id,teacher_id,teacher_user_id,invited_by,permissions)
       values(actor.institution_id,cid,target_teacher,p_teacher_user_id,actor.id,perms)
       on conflict(class_id,teacher_user_id) do update set teacher_id=excluded.teacher_id,invited_by=excluded.invited_by,permissions=excluded.permissions,status='pending',responded_at=null,updated_at=now()
       returning * into inv;
     select id into kind from public.catalog_notification_types where code='ANN';
     insert into public.notifications(institution_id,user_id,notification_type_id,title,message,data,read)
       values(actor.institution_id,p_teacher_user_id,kind,'Invitación a colaborar',actor.full_name||' te invita a colaborar en una clase.',
       jsonb_build_object('module','collaborations','invitationId',inv.id,'deepLink','/teacher/collaborations'),false);
   end loop;
 elsif p_action in ('accept','decline','revoke','update') then
   select * into inv from public.class_collaborators where id=p_invitation_id and institution_id=actor.institution_id for update;
   if not found then raise exception 'Invitación no encontrada.' using errcode='22023'; end if;
   if p_action in ('accept','decline') then
     if inv.teacher_user_id<>actor.id or inv.status<>'pending' or not exists(
       select 1 from public.teachers t join public.classes c on c.id=inv.class_id where t.id=inv.teacher_id and t.person_id=actor.person_id and t.active
         and c.active and t.institution_id=actor.institution_id and c.institution_id=actor.institution_id)
       or not exists(select 1 from public.user_roles ur join public.roles r on r.id=ur.role_id where ur.user_id=actor.id and r.code='teacher') then
       raise exception 'No puedes responder esta invitación.' using errcode='42501'; end if;
     update public.class_collaborators set status=case when p_action='accept' then 'active' else 'declined' end,responded_at=now(),updated_at=now() where id=inv.id;
   else
     if not public.class_permission(inv.class_id,'collaborators.manage') then raise exception 'Solo el titular o administración puede gestionar colaboradores.' using errcode='42501'; end if;
     if p_action='update' then
       if inv.status not in ('pending','active') then raise exception 'Invita de nuevo al profesor.' using errcode='22023'; end if;
       update public.class_collaborators set permissions=perms,updated_at=now() where id=inv.id;
     else update public.class_collaborators set status='revoked',updated_at=now() where id=inv.id; end if;
   end if;
 else raise exception 'Acción inválida.' using errcode='22023'; end if;
 return public.collaboration_workspace();
end $$;

-- Restrictive policies also protect direct Supabase requests; existing tenant
-- policies remain required. Granting class.view never grants write privileges.
do $$ declare tbl text; expr text; perm text; cmd text; begin
 for tbl,expr,perm in values
   ('classes','id','class.view'),('assignments','class_id','class.view'),
   ('evaluations','class_id','students.view'),
   ('submissions','(select class_id from public.assignments where id=assignment_id)','assignments.review'),
   ('grades','(select class_id from public.evaluations where id=evaluation_id)','students.view'),
   ('class_sessions','class_id','students.view'),
   ('attendances','(select class_id from public.class_sessions where id=class_session_id)','students.view')
 loop
   execute format('drop policy if exists class_scope_read on public.%I',tbl);
   execute format('create policy class_scope_read on public.%I as restrictive for select to authenticated using (public.teacher_class_read(%s,%L))',tbl,expr,perm);
 end loop;
 for tbl,expr,perm in values
   ('assignments','class_id','assignments.create'),
   ('assignment_files','(select class_id from public.assignments where id=assignment_id)','assignments.create'),
   ('evaluations','class_id','collaborators.manage'),('grades','(select class_id from public.evaluations where id=evaluation_id)','grades.write'),
   ('class_sessions','class_id','attendance.write'),('attendances','(select class_id from public.class_sessions where id=class_session_id)','attendance.write')
 loop
   foreach cmd in array array['insert','update','delete'] loop
     execute format('drop policy if exists class_scope_%s on public.%I',cmd,tbl);
     if cmd='insert' then
       execute format('create policy class_scope_insert on public.%I as restrictive for insert to authenticated with check (public.class_permission(%s,%L))',tbl,expr,perm);
     elsif cmd='update' then
       execute format('create policy class_scope_update on public.%I as restrictive for update to authenticated using (public.class_permission(%s,%L)) with check (public.class_permission(%s,%L))',tbl,expr,perm,expr,perm);
     else execute format('create policy class_scope_delete on public.%I as restrictive for delete to authenticated using (public.class_permission(%s,%L))',tbl,expr,perm); end if;
   end loop;
 end loop;
end $$;
