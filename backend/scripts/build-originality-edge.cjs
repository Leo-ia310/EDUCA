const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../..');
const destination = path.join(root, 'supabase/functions/nivra-originality/generated');
fs.mkdirSync(destination, { recursive: true });
for (const name of ['domain', 'extract-core']) {
  const source = fs.readFileSync(path.join(root, `backend/src/modules/assignments/originality/${name}.ts`), 'utf8');
  const output = '// Generated by backend/scripts/build-originality-edge.cjs from the Node implementation.\n' + source
    .replace(/\r\n/g, '\n').replace("from './domain'", "from './domain.ts'")
    .replace("from 'fflate'", "from 'npm:fflate@0.8.3'")
    .replace("from 'fast-xml-parser'", "from 'npm:fast-xml-parser@5.11.2'");
  const target = path.join(destination, `${name}.ts`);
  if (process.argv.includes('--check')) {
    if (!fs.existsSync(target) || fs.readFileSync(target, 'utf8') !== output) throw Error(`Stale Edge source: ${name}`);
  } else fs.writeFileSync(target, output);
}
console.log('Originality shared Edge sources are current.');
